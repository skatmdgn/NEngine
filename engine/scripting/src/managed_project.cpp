bool ManagedProjectGenerator::generate(
    const ManagedProjectConfig& config,
    ManagedProjectOutput& output,
    std::string* error) {

    if (config.project_root.empty() ||
        config.project_name.empty() ||
        config.target_framework.empty() ||
        config.runtime_framework_version.empty()) {
        set_error(
            error,
            "managed project requires project root and name");
        return false;
    }

    const auto generated_directory =
        config.project_root /
        ".nengine" /
        "Managed";

    std::error_code ec;
    std::filesystem::create_directories(
        generated_directory,
        ec);

    if (ec) {
        set_error(
            error,
            "could not create managed generation directory");
        return false;
    }

    output.project_path =
        generated_directory /
        (config.project_name + ".csproj");

    output.api_stub_path =
        generated_directory /
        "NEngine.API.cs";

    output.bridge_path =
        generated_directory /
        "NEngine.ManagedBridge.cs";

    output.runtime_config_path =
        generated_directory /
        (config.project_name +
         ".runtimeconfig.json");

    output.solution_path =
        config.project_root /
        (config.project_name + ".sln");

    std::ostringstream project;

    project
        << "<Project Sdk=\"Microsoft.NET.Sdk\">\n"
        << "  <PropertyGroup>\n"
        << "    <TargetFramework>"
        << xml_escape(
            config.target_framework)
        << "</TargetFramework>\n"
        << "    <LangVersion>latest</LangVersion>\n"
        << "    <Nullable>enable</Nullable>\n"
        << "    <GenerateRuntimeConfigurationFiles>true</GenerateRuntimeConfigurationFiles>\n"
        << "    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>\n"
        << "    <AssemblyName>"
        << xml_escape(config.project_name)
        << "</AssemblyName>\n"
        << "  </PropertyGroup>\n"
        << "  <ItemGroup>\n"
        << "    <Compile Include=\"../../Assets/Scripts/**/*.cs\" />\n"
        << "    <Compile Include=\"NEngine.API.cs\" />\n"
        << "    <Compile Include=\"NEngine.ManagedBridge.cs\" />\n"
        << "  </ItemGroup>\n";

    if (!config.packages.empty()) {
        project << "  <ItemGroup>\n";

        for (const auto& package :
             config.packages) {

            if (package.id.empty() ||
                package.version.empty()) {
                continue;
            }

            project
                << "    <PackageReference Include=\""
                << xml_escape(package.id)
                << "\" Version=\""
                << xml_escape(package.version)
                << "\" />\n";
        }

        project << "  </ItemGroup>\n";
    }

    project << "</Project>\n";

    constexpr std::string_view project_guid =
        "{A5DFE48B-DBA9-4B57-A5D2-E8FBA5903B35}";

    std::ostringstream solution;

    solution
        << "Microsoft Visual Studio Solution File, Format Version 12.00\r\n"
        << "# Visual Studio Version 17\r\n"
        << "VisualStudioVersion = 17.0.31903.59\r\n"
        << "MinimumVisualStudioVersion = 10.0.40219.1\r\n"
        << "Project(\"{FAE04EC0-301F-11D3-BF4B-00C04F79EFBC}\") = \""
        << config.project_name
        << "\", \".nengine\\Managed\\"
        << config.project_name
        << ".csproj\", \""
        << project_guid
        << "\"\r\n"
        << "EndProject\r\n"
        << "Global\r\n"
        << "\tGlobalSection(SolutionConfigurationPlatforms) = preSolution\r\n"
        << "\t\tDebug|Any CPU = Debug|Any CPU\r\n"
        << "\t\tRelease|Any CPU = Release|Any CPU\r\n"
        << "\tEndGlobalSection\r\n"
        << "\tGlobalSection(ProjectConfigurationPlatforms) = postSolution\r\n"
        << "\t\t" << project_guid << ".Debug|Any CPU.ActiveCfg = Debug|Any CPU\r\n"
        << "\t\t" << project_guid << ".Debug|Any CPU.Build.0 = Debug|Any CPU\r\n"
        << "\t\t" << project_guid << ".Release|Any CPU.ActiveCfg = Release|Any CPU\r\n"
        << "\t\t" << project_guid << ".Release|Any CPU.Build.0 = Release|Any CPU\r\n"
        << "\tEndGlobalSection\r\n"
        << "EndGlobal\r\n";

    if (!write_text(
            output.api_stub_path,
            api_stub(),
            error)) {
        return false;
    }

    if (!write_text(
            output.bridge_path,
            managed_bridge(
                config.project_name),
            error)) {
        return false;
    }

    DotnetRuntimeConfig runtime_config;
    runtime_config.target_framework =
        config.target_framework;
    runtime_config.framework_version =
        config.runtime_framework_version;

    if (!write_dotnet_runtime_config(
            output.runtime_config_path,
            runtime_config,
            error)) {
        return false;
    }

    if (!write_text(
            output.project_path,
            project.str(),
            error)) {
        return false;
    }

    if (!write_text(
            output.solution_path,
            solution.str(),
            error)) {
        return false;
    }

    return true;
}

std::vector<NuGetPackageReference>
ManagedProjectGenerator::load_package_manifest(
    const std::filesystem::path& path,
    std::string* error) {

    std::vector<NuGetPackageReference> result;

    std::ifstream input(
        path,
        std::ios::binary);

    if (!input) {
        return result;
    }

    std::string id;
    std::string version;

    while (input >> id >> version) {
        if (!id.empty() &&
            id.front() == '#') {

            std::string ignored;
            std::getline(input, ignored);
            continue;
        }

        if (id.empty() ||
            version.empty()) {
            continue;
        }

        result.push_back({
            std::move(id),
            std::move(version)
        });
    }

    if (!input.eof() && input.fail()) {
        set_error(
            error,
            "managed package manifest parse failed");
    }

    return result;
}

