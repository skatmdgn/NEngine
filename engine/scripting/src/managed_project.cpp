void set_error(
    std::string* error,
    std::string message) {

    if (error) {
        *error = std::move(message);
    }
}

std::string xml_escape(
    std::string_view value) {

    std::string result;
    result.reserve(value.size());

    for (const char ch : value) {
        switch (ch) {
        case '&': result += "&amp;"; break;
        case '<': result += "&lt;"; break;
        case '>': result += "&gt;"; break;
        case '"': result += "&quot;"; break;
        case '\'': result += "&apos;"; break;
        default: result.push_back(ch); break;
        }
    }

    return result;
}

bool write_text(
    const std::filesystem::path& path,
    std::string_view text,
    std::string* error) {

    std::ofstream output(
        path,
        std::ios::binary | std::ios::trunc);

    if (!output) {
        set_error(
            error,
            "could not open generated file: " +
                path.generic_string());
        return false;
    }

    output.write(
        text.data(),
        static_cast<std::streamsize>(
            text.size()));

    if (!output.good()) {
        set_error(
            error,
            "failed writing generated file: " +
                path.generic_string());
        return false;
    }

    return true;
}

std::string managed_bridge(
    std::string_view assembly_name) {

    std::ostringstream source;

    source
        << "// Generated by NEngine. Do not edit.\n"
        << "using System.Runtime.InteropServices;\n\n"
        << "namespace NEngine.Internal\n"
        << "{\n"
        << "    public static class NativeBridge\n"
        << "    {\n"
        << "        public const int AbiVersion = 1;\n\n"
        << "        [UnmanagedCallersOnly]\n"
        << "        public static int GetAbiVersion() => AbiVersion;\n\n"
        << "        public static string AssemblyName => \""
        << assembly_name
        << "\";\n"
        << "    }\n"
        << "}\n";

    return source.str();
}

